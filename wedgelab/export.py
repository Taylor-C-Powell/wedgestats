def to_json(
    spec: QQSpec,
    theme_key: str = "screen",
    options: PlotOptions | None = None,
    *,
    include_data: bool = True,
) -> str:
    """Serialise a specification, theme, and presentation options to JSON."""
    opts = options or PlotOptions()
    pos = spec.position
    payload: dict[str, Any] = {
        "wedgelab_session": 1,
        "spec": {
            "data": [float(v) for v in np.asarray(spec.data).ravel()] if include_data else None,
            "dist_key": spec.dist_key,
            "fit_method": spec.fit_method,
            "manual_params": list(spec.manual_params) if spec.manual_params else None,
            "position": {
                "name": pos.name,
                "expression": pos.expression,
                "lhs": pos.lhs,
                "description": pos.description,
                "citation": pos.citation,
                "latex": pos.latex,
                "derived_from": pos.derived_from,
                "parameters": [asdict(p) for p in pos.parameters],
            },
            "position_bindings": {k: float(v) for k, v in spec.position_bindings.items()},
            "line": spec.line,
            "envelope": spec.envelope,
            "alpha": spec.alpha,
            "standardize": spec.standardize,
            "detrend": spec.detrend,
            "bootstrap_reps": spec.bootstrap_reps,
            "random_state": spec.random_state,
            "label": spec.label,
        },
        "theme": theme_key,
        "options": asdict(opts),
    }
    return json.dumps(payload, indent=2)


def from_json(text: str, data: np.ndarray | None = None) -> tuple[QQSpec, str, PlotOptions]:
    """Restore a session written by :func:`to_json`.

    Parameters
    ----------
    text : str
        JSON produced by :func:`to_json`.
    data : np.ndarray or None
        Sample to use when the session was saved without its data.

    Returns
    -------
    tuple[QQSpec, str, PlotOptions]
        The specification, theme key, and presentation options.

    Raises
    ------
    ValueError
        If the payload is not a wedgelab session, or carries no data and none
        was supplied.
    """
    payload = json.loads(text)
    if payload.get("wedgelab_session") != 1:
        raise ValueError("not a wedgelab session file (version 1)")

    raw = payload["spec"]
    values = raw.get("data")
    if values is None:
        if data is None:
            raise ValueError("session carries no data; supply it explicitly")
        sample = np.asarray(data, dtype=float)
    else:
        sample = np.asarray(values, dtype=float)

    pos_raw = raw["position"]
    position = Formula(
        name=pos_raw["name"],
        expression=pos_raw["expression"],
        lhs=pos_raw.get("lhs", "p_i"),
        description=pos_raw.get("description", ""),
        parameters=tuple(Parameter(**p) for p in pos_raw.get("parameters", [])),
        citation=pos_raw.get("citation", ""),
        latex=pos_raw.get("latex", ""),
        derived_from=pos_raw.get("derived_from", ""),
    )

    manual = raw.get("manual_params")
    spec = QQSpec(
        data=sample,
        dist_key=raw["dist_key"],
        fit_method=raw["fit_method"],
        manual_params=tuple(manual) if manual else None,
        position=position,
        position_bindings=dict(raw.get("position_bindings", {})),
        line=raw["line"],
        envelope=raw["envelope"],
        alpha=raw["alpha"],
        standardize=raw["standardize"],
        detrend=raw["detrend"],
        bootstrap_reps=raw["bootstrap_reps"],
        random_state=raw["random_state"],
        label=raw["label"],
    )
    return spec, payload.get("theme", "screen"), PlotOptions(**payload.get("options", {}))


def write_session(
    path: str | Path,
    spec: QQSpec,
    theme_key: str = "screen",
    options: PlotOptions | None = None,
    *,
    include_data: bool = True,
) -> Path:
    """Write a session file and return its path."""
    target = Path(path).with_suffix(".wedgelab.json")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(to_json(spec, theme_key, options, include_data=include_data), encoding="utf-8")
    return target


def read_session(
    path: str | Path, data: np.ndarray | None = None
) -> tuple[QQSpec, str, PlotOptions]:
    """Read a session file written by :func:`write_session`."""
    return from_json(Path(path).read_text(encoding="utf-8"), data)
