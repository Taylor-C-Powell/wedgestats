_SCRIPT_TEMPLATE = '''"""Reproduce a wedgelab Q-Q figure.

Generated by wedgelab. Every choice behind the figure is spelled out below:
the plotting-position formula, the reference distribution and its estimator,
the reference line, the confidence envelope, and the publication theme.

Requires wedgestats and wedgelab on the import path.
"""

import numpy as np

from wedgelab.export import save_figure
from wedgelab.formula import Formula, Parameter
from wedgelab.plot import PlotOptions, render
from wedgelab.qq import QQSpec, compute

# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------
{data_block}

# ---------------------------------------------------------------------------
# Plotting positions
#
# {position_doc}
# ---------------------------------------------------------------------------
position = Formula(
    name={position_name!r},
    expression={position_expr!r},
    lhs={position_lhs!r},
    description={position_desc!r},
    parameters=({position_params}),
    citation={position_citation!r},
)

# ---------------------------------------------------------------------------
# Specification
# ---------------------------------------------------------------------------
spec = QQSpec(
    data=data,
    dist_key={dist_key!r},
    fit_method={fit_method!r},
    manual_params={manual_params!r},
    position=position,
    position_bindings={bindings!r},
    line={line!r},
    envelope={envelope!r},
    alpha={alpha!r},
    standardize={standardize!r},
    detrend={detrend!r},
    bootstrap_reps={bootstrap_reps!r},
    random_state={random_state!r},
    label={label!r},
)

result = compute(spec)

# ---------------------------------------------------------------------------
# Figure
# ---------------------------------------------------------------------------
options = PlotOptions(
    title={title!r},
    xlabel={xlabel!r},
    ylabel={ylabel!r},
    show_band={show_band!r},
    show_line={show_line!r},
    show_legend={show_legend!r},
    annotate={annotate!r},
    annotation_fields={annotation_fields!r},
    mark_outliers={mark_outliers!r},
    label_outliers={label_outliers!r},
    equal_aspect={equal_aspect!r},
    zero_line={zero_line!r},
)

fig = render(result, {theme_key!r}, options)
paths = save_figure(fig, {stem!r}, formats={formats!r})

print(result.caption())
for line in result.diagnostics.lines():
    print(line)
for path in paths:
    print("wrote", path)
'''


def _format_parameters(params: tuple[Parameter, ...]) -> str:
    """Render a parameter tuple as source code."""
    if not params:
        return ""
    parts = [
        "\n        Parameter(name={!r}, default={!r}, lower={!r}, upper={!r}, "
        "step={!r}, description={!r}),".format(
            p.name, p.default, p.lower, p.upper, p.step, p.description
        )
        for p in params
    ]
    return "".join(parts) + "\n    "


def _format_data(data: np.ndarray, data_path: str | Path | None, max_inline: int) -> str:
    """Render the data block: an inline literal, or a loader for a sidecar file."""
    if data_path is not None:
        return (
            f"# Loaded from the file this script was exported alongside.\n"
            f"data = np.loadtxt({str(data_path)!r})"
        )
    if data.size > max_inline:
        return (
            f"# {data.size} observations exceeded the inline limit of {max_inline}.\n"
            "# Export the data alongside the script and point this line at it.\n"
            'data = np.loadtxt("data.txt")'
        )
    values = ", ".join(repr(float(v)) for v in data)
    return f"data = np.array([{values}])"


def to_script(
    result: QQResult,
    theme_key: str = "screen",
    options: PlotOptions | None = None,
    *,
    stem: str = "qq_figure",
    formats: tuple[str, ...] = ("pdf", "png"),
    data_path: str | Path | None = None,
    max_inline: int = 5000,
) -> str:
    """Generate a standalone script that regenerates this figure.

    Parameters
    ----------
    result : QQResult
        The computed result to reproduce.
    theme_key : str
        Theme the figure was rendered with.
    options : PlotOptions or None
        Presentation options used.
    stem : str
        Output path stem the generated script will write to.
    formats : tuple[str, ...]
        Formats the generated script will write.
    data_path : str or Path or None
        When given, the script loads the data from this path instead of
        embedding it.
    max_inline : int
        Largest sample embedded as a literal.

    Returns
    -------
    str
        Python source.
    """
    spec = result.spec
    opts = options or PlotOptions()
    get_theme(theme_key)  # fail early on a bad theme key

    pos = spec.position
    doc = pos.description or "Plotting position rule."
    if pos.citation:
        doc = f"{doc}\n# Source: {pos.citation}"

    return _SCRIPT_TEMPLATE.format(
        data_block=_format_data(np.asarray(spec.data, dtype=float), data_path, max_inline),
        position_doc=doc,
        position_name=pos.name,
        position_expr=pos.expression,
        position_lhs=pos.lhs,
        position_desc=pos.description,
        position_params=_format_parameters(pos.parameters),
        position_citation=pos.citation,
        dist_key=spec.dist_key,
        fit_method=spec.fit_method,
        manual_params=spec.manual_params,
        bindings=dict(spec.position_bindings),
        line=spec.line,
        envelope=spec.envelope,
        alpha=spec.alpha,
        standardize=spec.standardize,
        detrend=spec.detrend,
        bootstrap_reps=spec.bootstrap_reps,
        random_state=spec.random_state,
        label=spec.label,
        title=opts.title,
        xlabel=opts.xlabel,
        ylabel=opts.ylabel,
        show_band=opts.show_band,
        show_line=opts.show_line,
        show_legend=opts.show_legend,
        annotate=opts.annotate,
        annotation_fields=opts.annotation_fields,
        mark_outliers=opts.mark_outliers,
        label_outliers=opts.label_outliers,
        equal_aspect=opts.equal_aspect,
        zero_line=opts.zero_line,
        theme_key=theme_key,
        stem=stem,
        formats=tuple(formats),
    )


