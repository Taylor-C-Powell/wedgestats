"""Export figures, reproducible scripts, and session files.

A figure is not reproducible because it is pretty; it is reproducible because
somebody can regenerate it.  :func:`to_script` writes a standalone Python file
that reconstructs the exact :class:`~wedgelab.qq.QQSpec` behind a figure --
plotting-position formula included -- and re-renders it.  Drop that file in
the supplementary material and the figure stops being a claim and becomes a
computation.

Session files (:func:`to_json` / :func:`from_json`) carry the same state for
the GUI, minus the data when it came from a file on disk.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any, Iterable

import numpy as np
from matplotlib.figure import Figure

from wedgelab.formula import Formula, Parameter
from wedgelab.plot import PlotOptions
from wedgelab.qq import QQResult, QQSpec
from wedgelab.theme import get_theme

__all__ = [
    "VECTOR_FORMATS",
    "RASTER_FORMATS",
    "save_figure",
    "to_script",
    "to_json",
    "from_json",
    "write_session",
    "read_session",
]

VECTOR_FORMATS: tuple[str, ...] = ("pdf", "svg", "eps")
RASTER_FORMATS: tuple[str, ...] = ("png", "tif")


def save_figure(
    fig: Figure,
    path: str | Path,
    formats: Iterable[str] = ("pdf",),
    dpi: int | None = None,
) -> list[Path]:
    """Write *fig* once per requested format.

    Parameters
    ----------
    fig : matplotlib.figure.Figure
        Figure to write.  Its physical size is preserved exactly; nothing is
        rescaled.
    path : str or Path
        Output path.  Any suffix is replaced by each format's own.
    formats : Iterable[str]
        Any of :data:`VECTOR_FORMATS` or :data:`RASTER_FORMATS`.
    dpi : int or None
        Raster resolution; ignored for vector formats.  ``None`` keeps the
        theme's setting.

    Returns
    -------
    list[Path]
        The files written.

    Raises
    ------
    ValueError
        If a requested format is not supported.
    """
    base = Path(path)
    known = set(VECTOR_FORMATS) | set(RASTER_FORMATS)
    written: list[Path] = []
    for fmt in formats:
        f = fmt.lower().lstrip(".")
        if f not in known:
            raise ValueError(
                f"unsupported format '{fmt}'; choose from {', '.join(sorted(known))}"
            )
        target = base.with_suffix(f".{f}")
        target.parent.mkdir(parents=True, exist_ok=True)
        kwargs: dict[str, Any] = {"format": f, "bbox_inches": "tight", "pad_inches": 0.02}
        if f in RASTER_FORMATS and dpi is not None:
            kwargs["dpi"] = dpi
        fig.savefig(target, **kwargs)
        written.append(target)
    return written


